// Regenerates a dot-lattice data file (e.g. hands-dots.ts, figma-dots.ts)
// consumed by DotField (src/shared/ui/DotField/DotField.tsx). Downsamples a
// source image to a cols x rows lattice (aspect-matched to the source) and
// stores one RGB triplet per cell, base64-encoded.
//
// Usage:
//   node scripts/extract-dot-field.mjs <src> --out <file> --export <NAME>
//     [--cols N] [--trim] [--chroma[=N]]
//
// --trim      Crop away a uniform white border before sampling.
// --chroma=N  Zero out (to black, so DotField's threshold skips them) any
//             cell whose colour is nearly gray/white/black — isolates
//             saturated subject matter (e.g. a colourful logo) from its
//             background. N is the max-min channel gap below which a cell
//             counts as unsaturated (default 24).

import sharp from "sharp";
import { writeFile } from "node:fs/promises";
import path from "node:path";

function parseArgs(argv) {
  const [src, ...rest] = argv;
  const flags = {
    src,
    cols: 280,
    out: null,
    exportName: "HANDS_DOTS",
    trim: false,
    chroma: null,
  };

  for (let i = 0; i < rest.length; i++) {
    const arg = rest[i];
    if (arg === "--trim") flags.trim = true;
    else if (arg === "--cols") flags.cols = Number.parseInt(rest[++i], 10);
    else if (arg === "--out") flags.out = rest[++i];
    else if (arg === "--export") flags.exportName = rest[++i];
    else if (arg.startsWith("--chroma")) {
      const [, value] = arg.split("=");
      flags.chroma = value ? Number.parseInt(value, 10) : 24;
    }
  }

  return flags;
}

const flags = parseArgs(process.argv.slice(2));
if (!flags.src || !flags.out) {
  console.error(
    "Usage: node scripts/extract-dot-field.mjs <src> --out <file> --export <NAME> [--cols N] [--trim] [--chroma[=N]]",
  );
  process.exit(1);
}

function isolateChroma(buffer, channels, threshold) {
  for (let i = 0; i < buffer.length; i += channels) {
    const r = buffer[i];
    const g = buffer[i + 1];
    const b = buffer[i + 2];
    const chroma = Math.max(r, g, b) - Math.min(r, g, b);
    if (chroma < threshold) {
      buffer[i] = 0;
      buffer[i + 1] = 0;
      buffer[i + 2] = 0;
    }
  }
}

async function main() {
  let pipeline = sharp(flags.src);
  if (flags.trim) {
    pipeline = pipeline.trim({ background: "#ffffff", threshold: 10 });
  }
  const source = await pipeline.toBuffer();

  const meta = await sharp(source).metadata();
  const rows = Math.round(flags.cols * (meta.height / meta.width));

  const { data, info } = await sharp(source)
    .resize(flags.cols, rows, { fit: "fill", kernel: "lanczos3" })
    .removeAlpha()
    .raw()
    .toBuffer({ resolveWithObject: true });

  if (flags.chroma !== null) isolateChroma(data, info.channels, flags.chroma);

  const base64 = Buffer.from(data).toString("base64");
  const relSrc = path.relative(process.cwd(), path.resolve(flags.src));

  const output = `// Generated by scripts/extract-dot-field.mjs — do not edit by hand.
// Source: ${relSrc} (${meta.width}x${meta.height})

/** One RGB triplet (3 bytes) per lattice cell, row-major, base64-encoded. */
export const ${flags.exportName} = {
  cols: ${flags.cols},
  rows: ${rows},
  pitchX: 1,
  pitchY: 1,
  data: "${base64}",
};
`;

  await writeFile(flags.out, output);
  console.log(
    `Wrote ${flags.out}: ${flags.cols}x${rows} cells, ${(base64.length / 1024).toFixed(1)}KB base64`,
  );
}

main();
