// Regenerates src/widgets/home/Hero/HandsField/hands-dots.ts from a source
// image. Downsamples the image to a cols x rows lattice (aspect-matched to
// the source) and stores one RGB triplet per cell, base64-encoded.
//
// Usage: node scripts/extract-dot-field.mjs <path-to-image> [cols]

import sharp from "sharp";
import { writeFile } from "node:fs/promises";
import path from "node:path";

const [, , srcArg, colsArg] = process.argv;
if (!srcArg) {
  console.error(
    "Usage: node scripts/extract-dot-field.mjs <path-to-image> [cols]",
  );
  process.exit(1);
}

const SRC = srcArg;
const COLS = colsArg ? Number.parseInt(colsArg, 10) : 280;
const OUT = "src/widgets/home/Hero/HandsField/hands-dots.ts";

async function main() {
  const meta = await sharp(SRC).metadata();
  const rows = Math.round(COLS * (meta.height / meta.width));

  const { data } = await sharp(SRC)
    .resize(COLS, rows, { fit: "fill", kernel: "lanczos3" })
    .removeAlpha()
    .raw()
    .toBuffer({ resolveWithObject: true });

  const base64 = Buffer.from(data).toString("base64");
  const relSrc = path.relative(process.cwd(), path.resolve(SRC));

  const output = `// Generated by scripts/extract-dot-field.mjs — do not edit by hand.
// Source: ${relSrc} (${meta.width}x${meta.height})

/** One RGB triplet (3 bytes) per lattice cell, row-major, base64-encoded. */
export const HANDS_DOTS = {
  cols: ${COLS},
  rows: ${rows},
  pitchX: 1,
  pitchY: 1,
  data: "${base64}",
};
`;

  await writeFile(OUT, output);
  console.log(
    `Wrote ${OUT}: ${COLS}x${rows} cells, ${(base64.length / 1024).toFixed(1)}KB base64`,
  );
}

main();
